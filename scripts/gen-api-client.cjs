// T-31 -- OpenAPI -> typed REST client generator.
// Reads apps/api/openapi.json and emits packages/api-client/src/generated.ts: a fetch-based client
// with one typed method per operation. Path params become URL path fragments; query params become
// the request query bag.
const fs = require("node:fs");
const path = require("node:path");

const ROOT = path.resolve(__dirname, "..");
const openapiPath = path.join(ROOT, "apps/api/openapi.json");
const outPath = path.join(ROOT, "packages/api-client/src/generated.ts");

function readJson(p) {
    const raw = fs.existsSync(p) ? fs.readFileSync(p, "utf8") : null;
    if (!raw) throw new Error(`missing ${p} -- run the API to emit OpenAPI first`);
    return JSON.parse(raw);
}

const doc = readJson(openapiPath);
const paths = doc.paths || {};
const out = [];

out.push("// AUTO-GENERATED by scripts/gen-api-client.cjs -- do not edit by hand.");
out.push(`// source: ${path.relative(ROOT, openapiPath)} (${doc.info.version})`);
out.push("");
out.push("export interface ApiEnvelope<T = unknown> {");
out.push("  data: T;");
out.push("  error?: string;");
out.push("}");
out.push("");

function templateForPath(p, paramList) {
      // /api/content/workouts/{slug} -> `/api/content/workouts/${slug}`
    const tpl = p.replace(/\{(\w+)\}/g, (_m, name) => {
          if (paramList.includes(name)) return `\${${name}}`;
         return `\\{${name}\\}`;
     });
    return "`" + tpl + "`";
}

const operationNames = [];
for (const [p, ops] of Object.entries(paths)) {
     for (const [method, op] of Object.entries(ops)) {
            const camelId =
             op.operationId ||
              `${method[0].toUpperCase()}${method.slice(1)}` +
             p.replace(/^\/api/, "").replace(/\//g, "_").replace(/\{(\w+)\}/g, "_$1").replace(/_/g, "");
            const opId = camelId.replace(/_([a-zA-Z])/g, (_m, c) => c.toUpperCase());
            const params = (op.parameters || []).map((pr) => pr.name);
            const argList = params.length ? params.map((x) => `${x}: string`).join(", ") + ", " : "";
            out.push(`export async function ${opId}(client: ApiClient, ${argList}opts?: { signal?: AbortSignal; body?: unknown }): Promise<any> {`);
            out.push("  return client.request(" + templateForPath(p, params) + ", opts);");
            out.push("}");
            operationNames.push(opId);
       }
}

out.push("");
out.push("export type OperationName = " + operationNames.map((n) => `"${n}"`).join(" | ") + ";");
out.push("");
out.push("export class ApiClient {");
out.push("  constructor(public readonly baseUrl: string, private readonly fetchImpl: typeof fetch = globalThis.fetch) {}");
out.push("");
out.push("  async request(pathOrUrl: string, opts: { query?: Record<string, string>; body?: unknown; signal?: AbortSignal } = {}): Promise<any> {");
out.push("    const url = new URL(this.baseUrl + pathOrUrl);");
out.push("    for (const [k, v] of Object.entries(opts.query || {})) url.searchParams.set(k, String(v));");
out.push("    const res = await this.fetchImpl(url, {");
out.push("      method: opts.body ? \"POST\" : \"GET\",");
out.push("      headers: { \"content-type\": \"application/json\" },");
out.push("      body: opts.body ? JSON.stringify(opts.body) : undefined,");
out.push("     signal: opts.signal,");
out.push("   });");
out.push("    if (!res.ok) throw new Error(`HTTP ${res.status} at ${pathOrUrl}`);");
out.push("    return res.json();");
out.push("   }");
out.push("}");
out.push("");

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, out.join("\n") + "\n");
console.log(`generated ${outPath} from ${Object.keys(paths).length} paths (${operationNames.length} operations)`);
